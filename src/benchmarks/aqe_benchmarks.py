"""Pure Adaptive Query Execution (AQE) Benchmark Module.

Isolates AQE performance across both uniform and skewed transaction datasets
without any manual join hints or key salting interventions.
"""

import argparse
from pathlib import Path
import time
from typing import Dict, Any, List

from pyspark.sql import SparkSession
from tabulate import tabulate

from src.utils.spark_session import get_spark_session
from src.utils.metrics import MetricsCollector


def benchmark_aqe_run(
    spark: SparkSession,
    collector: MetricsCollector,
    tx_path: str,
    cust_path: str,
    aqe_enabled: bool,
    dataset_name: str,
    join_key: str = "customer_id",
) -> Dict[str, Any]:
    """Executes a pure join with AQE explicitly turned ON or OFF."""
    # Force Sort-Merge Join to isolate AQE's shuffle and skew-handling capabilities
    spark.conf.set("spark.sql.autoBroadcastJoinThreshold", "-1")

    # Dynamic AQE Configuration (Spark 3.x compliant keys)
    spark.conf.set("spark.sql.adaptive.enabled", str(aqe_enabled).lower())

    if aqe_enabled:
        spark.conf.set("spark.sql.adaptive.skewJoin.enabled", "true")
        spark.conf.set("spark.sql.adaptive.skewJoin.skewedPartitionFactor", "2")
        spark.conf.set(
            "spark.sql.adaptive.skewJoin.skewedPartitionThresholdInBytes", "1MB"
        )

    status_label = "AQE ON" if aqe_enabled else "AQE OFF"
    print(f"Running Join [{status_label}] on [{dataset_name} Data]...")

    df_tx = spark.read.parquet(tx_path)
    df_cust = spark.read.parquet(cust_path)

    # 1. Capture completed stage IDs prior to query execution
    stages_before = collector.get_completed_stage_ids()

    start_time = time.time()

    # Pure standard join - zero hints, zero custom logic
    df_joined = df_tx.join(df_cust, on=join_key, how="inner")
    result_count = df_joined.count()

    elapsed_time = round(time.time() - start_time, 3)

    # 2. Aggregate metrics for all stages generated by this query run
    metrics = collector.get_job_stage_metrics(stage_ids_before=stages_before)

    throughput = round(result_count / elapsed_time, 2) if elapsed_time > 0 else 0.0

    print(f"  Completed in {elapsed_time:.3f}s | Result count: {result_count:,}\n")

    return {
        "dataset": dataset_name,
        "aqe_status": "ON" if aqe_enabled else "OFF",
        "execution_time_s": elapsed_time,
        "result_count": result_count,
        "throughput_rps": throughput,
        "shuffle_read_mb": metrics.get("shuffle_read_mb", 0.0),
        "shuffle_write_mb": metrics.get("shuffle_write_mb", 0.0),
        "memory_spill_mb": metrics.get("memory_spill_mb", 0.0),
        "skew_ratio": metrics.get("skew_ratio", 1.0),
    }


def run_aqe_benchmarks(
    data_dir: str = "data/raw",
    tx_uniform: str = "transactions_uniform.parquet",
    tx_skewed: str = "transactions_skewed.parquet",
    cust: str = "customers.parquet",
    join_key: str = "customer_id",
) -> List[Dict[str, Any]]:
    """Runs isolated AQE ON vs OFF benchmarks across uniform and skewed datasets."""
    spark = get_spark_session(app_name="AQE_Benchmark")
    collector = MetricsCollector()

    base_path = Path(data_dir)
    cust_path = str(base_path / cust)
    tx_uniform_path = str(base_path / tx_uniform)
    tx_skewed_path = str(base_path / tx_skewed)

    runs = [
        {"tx_path": tx_uniform_path, "aqe": False, "name": "Uniform"},
        {"tx_path": tx_uniform_path, "aqe": True, "name": "Uniform"},
        {"tx_path": tx_skewed_path, "aqe": False, "name": "Skewed"},
        {"tx_path": tx_skewed_path, "aqe": True, "name": "Skewed"},
    ]

    results = []
    print("\n==================================================")
    print("      STARTING AQE ISOLATION BENCHMARKS           ")
    print("==================================================\n")

    for run in runs:
        res = benchmark_aqe_run(
            spark=spark,
            collector=collector,
            tx_path=run["tx_path"],
            cust_path=cust_path,
            aqe_enabled=run["aqe"],
            dataset_name=run["name"],
            join_key=join_key,
        )
        results.append(res)

    # Print Formatted Summary Table
    headers = [
        "Dataset",
        "AQE Status",
        "Exec Time (s)",
        "Throughput (RPS)",
        "Shuffle Read",
        "Memory Spill",
        "Skew Ratio",
    ]

    table_data = []
    for r in results:
        table_data.append([
            r["dataset"],
            r["aqe_status"],
            f"{r['execution_time_s']:.3f}s",
            f"{int(r['throughput_rps']):,}",
            f"{r['shuffle_read_mb']:.2f} MB",
            f"{r['memory_spill_mb']:.2f} MB",
            f"{r['skew_ratio']:.1f}x",
        ])

    print("\n==================================================")
    print("             BENCHMARK SUMMARY RESULTS            ")
    print("==================================================")
    print(tabulate(table_data, headers=headers, tablefmt="grid"))
    print("==================================================\n")

    return results


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run PySpark Isolated AQE Benchmark")
    parser.add_argument(
        "--data-dir",
        type=str,
        default="data/raw",
        help="Directory containing dataset Parquet files",
    )
    parser.add_argument(
        "--tx-uniform",
        type=str,
        default="transactions_uniform.parquet",
        help="Uniform transactions file",
    )
    parser.add_argument(
        "--tx-skewed",
        type=str,
        default="transactions_skewed.parquet",
        help="Skewed transactions file",
    )
    parser.add_argument(
        "--cust",
        type=str,
        default="customers.parquet",
        help="Customers lookup file",
    )
    parser.add_argument(
        "--join-key", type=str, default="customer_id", help="Join key column"
    )

    args = parser.parse_args()

    run_aqe_benchmarks(
        data_dir=args.data_dir,
        tx_uniform=args.tx_uniform,
        tx_skewed=args.tx_skewed,
        cust=args.cust,
        join_key=args.join_key,
    )